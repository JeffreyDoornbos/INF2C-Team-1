"""CH-013 PostgreSQL acceptance checks. Only creates randomly named test DBs."""
import argparse
import hashlib
import json
from decimal import Decimal
from pathlib import Path
import subprocess
import sys
import tempfile
import uuid

sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'database/postgresql'))
import import_test_json as importer
from test_validation import fixture,write_fixture


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--container',required=True)
    parser.add_argument('--schema',type=Path,required=True,help='SQL generated by dotnet ef migrations script')
    parser.add_argument('--source',type=Path,default=importer.legacy.ROOT/'data')
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    created=[];checks=[]
    def sql(db,statement):
        result=subprocess.run(['docker','exec','-i',args.container,'psql','-XAtq','-v','ON_ERROR_STOP=1',
                               '-U','cargohub_test','-d',db],input=statement,text=True,capture_output=True)
        if result.returncode:raise RuntimeError('Test setup/query failed: '+result.stderr)
        return result.stdout
    def database(migrate=True):
        db='cargohub_import_test_'+uuid.uuid4().hex
        sql('postgres',f'CREATE DATABASE "{db}";');created.append(db)
        if migrate:sql(db,args.schema.read_text())
        return db
    def check(condition,description):
        if not condition:raise AssertionError(description)
        checks.append(description);print('PASS: '+description,flush=True)
    def counts(db):
        return {t:int(sql(db,f'SELECT count(*) FROM public."{t}";').strip()) for t,_ in importer.legacy.ENTITIES}
    def sequence_state(db):
        return sql(db,"SELECT row_to_json(s) FROM (SELECT sequencename,last_value FROM pg_sequences WHERE schemaname='public' ORDER BY sequencename) s;")
    def compare_all_fields(db,source):
        tables,_=importer.validate(source)
        for table,data in tables.items():
            order=','.join(importer.legacy.quoted(k) for k in importer.primary(table))
            lines=sql(db,f'SET TIME ZONE \'UTC\'; SELECT row_to_json(t) FROM public."{table}" t ORDER BY {order};').splitlines()
            actual=[json.loads(line,parse_float=Decimal) for line in lines if line.startswith('{')]
            def normalized(row):
                result=[]
                for column,kind in data['columns']:
                    v=importer.legacy.convert_value(table,column,kind,row[column])
                    if v is not None and kind=='decimal':v=Decimal(v)
                    if v is not None and kind=='DateTimeOffset':v=importer.legacy.parse_timestamp(v)
                    result.append(v)
                return tuple(result)
            expected=[]
            for entry in data['accepted']:
                values=[]
                for col,kind in data['columns']:
                    v=entry['values'][col]
                    if v is not None and kind=='decimal':v=Decimal(v)
                    if v is not None and kind=='DateTimeOffset':v=importer.legacy.parse_timestamp(v)
                    values.append(v)
                expected.append(tuple(values))
            check(sorted(actual_row for actual_row in map(normalized,actual))==sorted(expected),
                  f'All accepted rows and fields match PostgreSQL: {table}')
    try:
        db=database()
        code,report=importer.run(args.source,args.output/'full-import.json',db,container=args.container)
        check(code==0 and report['status']=='imported','Full relational source copy imported into migrated empty test DB')
        check(report['summary']['read']==report['summary']['imported']+report['summary']['rejected'],
              'Read = imported + rejected')
        check(report['database_counts']==report['expected_counts'],'Database counts equal accepted source counts')
        check(report['database_inventory_totals']==report['expected_inventory_totals'],
              'All inventory totals and available stock equal accepted source totals')
        check(report['source_hashes_unchanged'],'Source hashes unchanged after full import')
        compare_all_fields(db,args.source)
        before=counts(db)
        code,repeated=importer.run(args.source,args.output/'repeat-refused.json',db,container=args.container)
        check(code==2 and repeated['status']=='not_imported' and counts(db)==before,
              'Repeat refused and all existing counts unchanged')
        compare_all_fields(db,args.source)
        tables,_=importer.validate(args.source)
        for table,data in tables.items():
            if 'id' in [c for c,_ in data['columns']]:
                expected=max([0]+[int(e['values']['id']) for e in data['accepted']])+1
                actual=int(sql(db,f"SELECT nextval(pg_get_serial_sequence('public.\"{table}\"','id'));").strip())
                check(actual==expected,'Next generated ID follows imported IDs: '+table)
        with tempfile.TemporaryDirectory() as folder:
            source=Path(folder)/'data';source.mkdir();data=fixture()
            data['inventory'].append(dict(data['inventory'][0]))
            data['order_item'].append({**data['order_item'][0],'id':2,'item_id':999})
            data['shipment_item'][0]['amount']=0
            data['transfer'][0]['transfer_status']='Unknown'
            write_fixture(source,data)
            mixed_db=database()
            code,mixed=importer.run(source,args.output/'mixed-rejections.json',mixed_db,container=args.container)
            check(code==0 and mixed['summary']['rejected']==6,
                  'Mixed import reports both duplicates, orphan, invalid amount/status and rejected-parent child')
            check(all(f['read']==f['imported']+f['rejected'] for f in mixed['files'].values()),
                  'Mixed report accounts for every record per table')
            check(mixed['database_inventory_totals']['quantity_on_hand']==0,
                  'Rejected inventory is excluded from source/database reconciliation')
            check(all(e['reasons'] for f in mixed['files'].values() for e in f['rejections']),
                  'Every rejected record has an indexed reason')
            compare_all_fields(mixed_db,source)
            check(mixed['source_hashes_unchanged'],'Mixed fixture source hashes unchanged')
        missing=database(False)
        code,r=importer.run(args.source,args.output/'missing-migrations.json',missing,container=args.container)
        check(code==2 and r['summary']['imported']==0,'Missing EF migrations block all import writes')
        failure=database()
        sql(failure,'ALTER TABLE public.transfer_item ADD CONSTRAINT ch013_injected_failure CHECK (amount < 0) NOT VALID;')
        sequences_before=sequence_state(failure)
        code,r=importer.run(args.source,args.output/'rollback.json',failure,container=args.container)
        check(code==2 and r['status']=='not_imported' and all(n==0 for n in counts(failure).values()),
              'Injected late COPY failure rolls back every table')
        check(sequence_state(failure)==sequences_before,'Rollback preserves original sequence states')
        sql(failure,'ALTER TABLE public.transfer_item DROP CONSTRAINT ch013_injected_failure;')
        code,r=importer.run(args.source,args.output/'retry-after-rollback.json',failure,container=args.container)
        check(code==0 and r['database_counts']==report['database_counts'],'Retry after complete rollback succeeds without reset')
    finally:
        for db in created:sql('postgres',f'DROP DATABASE "{db}" WITH (FORCE);')
    (args.output/'acceptance.json').write_text(json.dumps({'checks_passed':len(checks),'checks':checks,
        'test_databases_removed':len(created)},indent=2)+'\n')
    print(f'PASS: {len(checks)} PostgreSQL checks; {len(created)} temporary databases removed.')


if __name__=='__main__':main()
