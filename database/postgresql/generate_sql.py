"""Generate a self-contained psql import from the original CargoHub JSON files."""

import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path(__file__).resolve().parent
TABLES = [
    "warehouse", "client", "supplier", "item_line", "item_group", "item_type",
    "location", "item", "inventory", "order", "order_item", "shipment",
    "shipment_item", "transfer", "transfer_item", "user",
]
FOREIGN_KEYS = {
    "location": {"warehouse_id": "warehouse"},
    "item": {
        "supplier_id": "supplier", "item_line_id": "item_line",
        "item_group_id": "item_group", "item_type_id": "item_type",
    },
    "inventory": {"item_id": "item", "location_id": "location"},
    "order": {
        "client_id": "client", "ship_to_client_id": "client",
        "bill_to_client_id": "client", "warehouse_id": "warehouse",
    },
    "order_item": {"order_id": "order", "item_id": "item"},
    "shipment": {"order_id": "order"},
    "shipment_item": {"shipment_id": "shipment", "item_id": "item"},
    "transfer": {"from_location_id": "location", "to_location_id": "location"},
    "transfer_item": {"transfer_id": "transfer", "item_id": "item"},
}
# Existing location codes and order references are not unique in the source.
UNIQUE_COLUMNS = {
    "warehouse": ["code"], "supplier": ["code"], "item": ["code", "barcode"],
    "shipment": ["reference"], "transfer": ["reference"],
    "user": ["app", "api_key"],
}
TIMESTAMPS = {"created_at", "updated_at", "order_date", "request_date", "shipment_date"}
POSITIVE_COLUMNS = {"amount", "min_purchase_qty", "case_size", "order_multiple"}
NONNEGATIVE_COLUMNS = {
    "quantity_on_hand", "quantity_expected", "quantity_ordered", "quantity_allocated",
    "unit_weight", "unit_price",
}


def quoted(value):
    return '"' + value.replace('"', '""') + '"'


def table_name(table):
    return "cargohub." + quoted(table)


def column_type(table, column, values):
    if column == "id":
        return "bigint GENERATED BY DEFAULT AS IDENTITY"
    if column.endswith("_id"):
        return "bigint"
    if column in TIMESTAMPS:
        return "timestamptz"
    if column in {"unit_price", "unit_weight"}:
        return "numeric"
    if table == "user" and column == "endpoint_access":
        return "jsonb"
    non_null_types = {type(v) for v in values if v is not None}
    if non_null_types == {int}:
        return "bigint"
    if non_null_types == {str}:
        return "text"
    raise ValueError(f"Unsupported column type: {table}.{column}")


def copy_value(value):
    if value is None:
        return r"\N"
    if isinstance(value, (dict, list)):
        value = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    elif isinstance(value, bool):
        value = "true" if value else "false"
    else:
        value = str(value)
    return (value.replace("\\", "\\\\").replace("\t", "\\t")
            .replace("\n", "\\n").replace("\r", "\\r"))


def main():
    data = {}
    columns = {}
    hashes = {}
    for table in TABLES:
        raw = (ROOT / "data" / f"{table}.json").read_bytes()
        rows = json.loads(raw)
        if not isinstance(rows, list) or not rows:
            raise ValueError(f"Expected a nonempty array in {table}.json")
        fields = list(rows[0])
        if any(set(row) != set(fields) for row in rows):
            raise ValueError(f"Inconsistent columns in {table}.json")
        data[table] = rows
        columns[table] = fields
        hashes[table] = hashlib.sha256(raw).hexdigest()

    for table, rows in data.items():
        keys = ["item_id", "location_id"] if table == "inventory" else ["app"] if table == "user" else ["id"]
        counts = Counter(tuple(row[key] for key in keys) for row in rows)
        if any(count > 1 for count in counts.values()):
            raise ValueError(f"Duplicate primary key in {table}")
        for column, parent in FOREIGN_KEYS.get(table, {}).items():
            ids = {row["id"] for row in data[parent]}
            if any(row[column] is not None and row[column] not in ids for row in rows):
                raise ValueError(f"Missing foreign key in {table}.{column}")
        for column in UNIQUE_COLUMNS.get(table, []):
            if len({row[column] for row in rows}) != len(rows):
                raise ValueError(f"Duplicate unique value in {table}.{column}")
        for column in columns[table]:
            vals = [row[column] for row in rows if row[column] is not None]
            if column in POSITIVE_COLUMNS and any(v <= 0 for v in vals):
                raise ValueError(f"Nonpositive value in {table}.{column}")
            if column in NONNEGATIVE_COLUMNS and any(v < 0 for v in vals):
                raise ValueError(f"Negative value in {table}.{column}")

    ddl = [
        "-- CargoHub PostgreSQL schema. Source field names are preserved.",
        "-- Run in an empty schema; existing tables are never deleted or overwritten.",
        "CREATE SCHEMA cargohub;", "",
    ]
    for table in TABLES:
        definitions = []
        for column in columns[table]:
            vals = [row[column] for row in data[table]]
            definition = f"    {quoted(column)} {column_type(table, column, vals)}"
            if column in TIMESTAMPS:
                definition += " DEFAULT CURRENT_TIMESTAMP"
            if not any(v is None for v in vals):
                definition += " NOT NULL"
            definitions.append(definition)
        keys = ["item_id", "location_id"] if table == "inventory" else ["app"] if table == "user" else ["id"]
        definitions.append("    PRIMARY KEY (" + ", ".join(map(quoted, keys)) + ")")
        for column, parent in FOREIGN_KEYS.get(table, {}).items():
            definitions.append(f"    FOREIGN KEY ({quoted(column)}) REFERENCES {table_name(parent)} (id) ON DELETE RESTRICT")
        for column in UNIQUE_COLUMNS.get(table, []):
            if column not in keys:
                definitions.append(f"    UNIQUE ({quoted(column)})")
        for column in columns[table]:
            if column in POSITIVE_COLUMNS:
                definitions.append(f"    CHECK ({quoted(column)} > 0)")
            elif column in NONNEGATIVE_COLUMNS:
                definitions.append(f"    CHECK ({quoted(column)} >= 0)")
        if table == "transfer":
            definitions.append("    CHECK (from_location_id <> to_location_id)")
        if table == "user":
            definitions.append("    CHECK (jsonb_typeof(endpoint_access) = 'object')")
        ddl.append(f"CREATE TABLE {table_name(table)} (\n" + ",\n".join(definitions) + "\n);\n")

    for table, references in FOREIGN_KEYS.items():
        for column in references:
            if table == "inventory" and column == "item_id":
                continue  # Already covered by the first column of the composite PK.
            ddl.append(f"CREATE INDEX {quoted('ix_' + table + '_' + column)} ON {table_name(table)} ({quoted(column)});")
    ddl += [
        'CREATE INDEX ix_order_reference ON cargohub."order" (reference);',
        'CREATE INDEX ix_location_code ON cargohub."location" (code);',
        "", "-- Several shipments may reference the same order; order_id is not unique.",
        "-- Application code must set updated_at when modifying records.", "",
    ]
    schema = "\n".join(ddl)
    (OUTPUT / "schema.sql").write_text(schema, encoding="utf-8")

    bootstrap = [
        "-- Generated by generate_sql.py from all 16 JSON files in data/.",
        "-- Execute with psql, not with a generic SQL editor (psql commands are used).",
        "-- Never deletes existing data. An existing cargohub schema causes a rollback.",
        r"\set ON_ERROR_STOP on", r"\encoding UTF8", "",
        "SELECT 'CREATE DATABASE cargohub WITH ENCODING ''UTF8'' TEMPLATE template0'",
        "WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'cargohub')",
        r"\gexec", r"\connect cargohub", "", "BEGIN;", "SET TIME ZONE 'UTC';", schema,
    ]
    with (OUTPUT / "cargohub.sql").open("w", encoding="utf-8", newline="\n") as output:
        output.write("\n".join(bootstrap) + "\n")
        for table in TABLES:
            output.write(f"-- Source: data/{table}.json | rows: {len(data[table])} | sha256: {hashes[table]}\n")
            output.write(f"COPY {table_name(table)} (" + ", ".join(map(quoted, columns[table])) + ") FROM stdin;\n")
            for row in data[table]:
                output.write("\t".join(copy_value(row[column]) for column in columns[table]) + "\n")
            output.write("\\.\n\n")
        for table in TABLES:
            if "id" in columns[table]:
                output.write(f"SELECT setval(pg_get_serial_sequence('{table_name(table)}', 'id'), (SELECT MAX(id) FROM {table_name(table)}), true);\n")
        output.write("\n-- Check exact row counts before committing the import.\nDO $validation$\nBEGIN\n")
        for table in TABLES:
            count = len(data[table])
            output.write(f"    IF (SELECT COUNT(*) FROM {table_name(table)}) <> {count} THEN\n")
            output.write(f"        RAISE EXCEPTION 'Unexpected record count in {table}';\n    END IF;\n")
        output.write("END;\n$validation$;\n\nCOMMIT;\nANALYZE;\n")

    manifest = {
        "database": "cargohub", "schema": "cargohub",
        "total_records": sum(len(rows) for rows in data.values()),
        "sources": {table: {"file": f"data/{table}.json", "rows": len(data[table]), "sha256": hashes[table]} for table in TABLES},
    }
    (OUTPUT / "import-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Generated cargohub.sql and schema.sql for {manifest['total_records']} records.")


if __name__ == "__main__":
    main()
